/**
 * 全站字号刻度（Typography Scale）
 * =================================
 *
 * 为什么需要这个文件
 * ------------------
 * 本项目 HUD 面板密集（顶栏 / 气场仪 / 道历 / 五行 / 八卦 / 弹窗），
 * 早期各处直接写死 `text-[10px]`、`text-xs` 等魔法数字，
 * 改一次字号要在十几个文件里搜替换，极易漏改且无法保证视觉层级一致。
 *
 * 排查记录（2026-10-07）
 * ----------------------
 * 用脚本盘点全页后发现：86 个可见文本节点中 **66.3% 小于 12px，最小仅 9px**。
 * 用户反馈「看不清」的根因就是这批小字，而非单个面板的问题。
 *
 * 放大策略：非线性（小字提更多）
 * --------------------------------
 * 人眼对「已经能辨认但偏小」的字和「完全看不清」的字，容忍度不同。
 * 9px 这类字放大 1.5 倍到 13.5px 是从「看不清」跨到「能看清」，
 * 而 12px 放大 1.5 倍到 18px 只是「更舒服」——同样的倍数，
 * 对小字的收益远大于大字。故采用非线性刻度：
 *
 *   9px  → 14px   (×1.56)   ← 跨越可读阈值，收益最大
 *   10px → 15px   (×1.50)
 *   11px → 16px   (×1.45)
 *   12px → 18px   (×1.50)   ← 面板主信息
 *   14px → 20px   (×1.43)   ← 面板标题
 *   16px → 22px   (×1.38)
 *   18px → 25px   (×1.39)
 *
 * 层级说明
 * --------
 * - meta   辅助说明、脚注、节气副标题（最小可接受 14px）
 * - label  面板内的字段标签，如「罗盘天向」
 * - body   面板正文
 * - title  面板标题
 * - hero   强调数字、当前山名等
 *
 * 用法
 * ---
 * 直接用 Tailwind 任意值类名，保持与项目现有风格一致：
 *
 *   <span className={T.meta}>二十四山 · 每山十五度</span>
 *
 * 或需要行高/字重一并控制时：
 *
 *   <span className={cx(T.meta, 'text-[#c5a059]/75')}>...</span>
 */

/** 面板文字刻度（px 值，供脚本审计与需要 inline style 的场景使用） */
export const FONT_PX = {
  meta: 14,
  label: 15,
  body: 16,
  title: 18,
  heading: 20,
  hero: 25,
} as const;

/**
 * 与 FONT_PX 一一对应的 Tailwind 类名。
 * 用 `size-*` 而不是裸类名，是为了可读性——调用处一眼能看出是「提示级」还是「标题级」。
 */
export const T = {
  /** 辅助说明 / 脚注，如「二十四山 · 每山十五度」 */
  meta: 'text-[14px] leading-tight',
  /** 字段标签，如「罗盘天向」「周天度数」 */
  label: 'text-[15px] leading-tight',
  /** 面板正文 */
  body: 'text-[16px] leading-tight',
  /** 面板标题，如「气场共鸣仪」 */
  title: 'text-[18px] leading-tight',
  /** 区块标题，比 title 更大一号 */
  heading: 'text-[20px] leading-tight',
  /** 强调数字 / 当前值 */
  hero: 'text-[25px] leading-none',
} as const;

/** 面板最小可接受字号（px）。审计脚本据此判定「是否达标」 */
export const MIN_READABLE_PX = 13;

/**
 * 面板宽度同步放大系数。
 *
 * 字号变大会导致文字换行，容器宽度必须同步放宽，
 * 否则会出现「本来一行变成两行」的高度跳变。
 * 各面板原来的 285px / 265px 全部乘以约 1.3。
 *
 * 分档（2026-10-07 补充）
 * ----------------------
 * 右侧栏改为 xl(1280) 分档，而非单一值。原因是读数面板相对全屏居中、
 * 右栏绝对定位贴右，两者会在窄视口横向对撞（1024x768 实测重叠 66x63px）。
 * 探测各档宽度对折行的影响后选定：
 *   - 360px（大屏舒适值，道历 h=320）
 *   - 300px（窄视口「免费下限」：道历 h=320、折行 16 处，与 360px 完全一致；
 *           再窄到 280px 高度跳到 344px 开始劣化）
 * 详见 scripts/probe-aside-width.mjs。
 */
export const PANEL_WIDTH = {
  /** 右侧栏（道历 / 五行 / 八卦）宽屏档，xl 及以上 */
  rightColumn: 360,
  /** 右侧栏窄屏档，xl 以下 */
  rightColumnNarrow: 300,
  /** 左侧气场仪 */
  gauge: 340,
} as const;
