"""定论诊断：为什么用户看到「金木水火土被分割成2个环，还错位」

盘面结构（半径由内到外）：
  r0..r1  八卦环   文字白 + 卦爻
  r1..r2  五行环   扇区填色 + 五行字    <-- 用户说"被分成两个环"的内环
  r2..r3  节气环   24节气文字，按季节着色  <-- 用户误认为的"另一个环"
  r3..r4  二十四山环

两环物理紧邻（r2 是共用边框），且**用色几乎一一对应**：
  节气环 春=#4ade80(绿)   夏=#ff7875(粉)   秋=#fde047(黄)   冬=#60a5fa(蓝)
  五行环 木=绿            火=红            土/金=黄白        水=蓝

→ 绿色扇区(木)紧挨着绿色文字(春)，肉眼自然读成"绿色被切成内外两条带"。

本脚本量化：两环的**角度边界是否对齐**。
"""

# 五行主弧（来自 wuxingArc.ts 实测输出）
WUXING = [
    ('水', 330, 390),   # 跨 0°，即 330..30
    ('土', 30, 60),
    ('木', 60, 120),
    ('土', 120, 135),
    ('木', 135, 150),   # 巽 副段
    ('火', 150, 210),
    ('土', 210, 240),
    ('金', 240, 300),
    ('土', 300, 315),
    ('金', 315, 330),   # 乾 副段
]

# 节气环季节分组（来自 taoCalendar.ts 实测）
SEASON = [
    ('冬', [(0, '冬至'), (15, '小寒'), (30, '大寒')]),
    ('春', [(45, '立春'), (60, '雨水'), (75, '惊蛰'), (90, '春分'), (105, '清明'), (120, '谷雨')]),
    ('夏', [(135, '立夏'), (150, '小满'), (165, '芒种'), (180, '夏至'), (195, '小暑'), (210, '大暑')]),
    ('秋', [(225, '立秋'), (240, '处暑'), (255, '白露'), (270, '秋分'), (285, '寒露'), (300, '霜降')]),
    ('冬', [(315, '立冬'), (330, '小雪'), (345, '大雪')]),
]

SEASON_SPAN = {}
for s, items in SEASON:
    SEASON_SPAN[s] = (items[0][0], items[-1][0] + 15)

# 五行主字颜色（vivid）vs 节气文字颜色
EL_COLOR = {'木': '#4ade80', '火': '#ff4d4f', '土': '#facc15', '金': '#ffffff', '水': '#38bdf8'}
SE_COLOR = {'春': '#4ade80', '夏': '#ff7875', '秋': '#fde047', '冬': '#60a5fa'}

print('=' * 84)
print('一、两环用色对照（这是"看起来被拆成两个环"的直接原因）')
print('=' * 84)
print('  五行环主字色        节气环文字色      是否同色系')
print('-' * 84)
pairs = [('木', '春'), ('火', '夏'), ('金', '秋'), ('水', '冬')]
for el, se in pairs:
    print('  %-8s       %-8s        %s' % (
        el + ' ' + EL_COLOR[el], se + ' ' + SE_COLOR[se],
        '★ 几乎同色' if el in ('木', '火', '水') else '★ 黄色系相近'))

print()
print('=' * 84)
print('二、角度边界对齐检查（这是"错位"的量化依据）')
print('=' * 84)
print('  五行主弧区间        节气季节区间      起始角差   结束角差')
print('-' * 84)
main = {'水': (330, 390), '木': (60, 120), '火': (150, 210), '金': (240, 300)}
for el, se in pairs:
    ws, we = main[el]
    ss, se_end = SEASON_SPAN[se]
    if el == '水':
        ss_n, se_n = 330, 30      # 水跨 0°，归一化显示
    else:
        ss_n, se_n = ss, se_end
    d_s = (ss - ws) % 360
    d_e = (se_end - we) % 360
    flag = ''
    if d_s != 0 or d_e != 0:
        flag = '  <== 边界不对齐'
    print('  %s %3d~%3d      %s %3d~%3d      +%3d      +%3d%s' % (
        el, ws % 360, we % 360, se, ss % 360, se_end % 360, d_s, d_e, flag))

print()
print('=' * 84)
print('三、逐 15° 格子核对：内环五行 vs 外环节气颜色是否"打架"')
print('=' * 84)
print('  角度   二十四山   五行(内环)   节气(外环)   视觉后果')
print('-' * 84)
MTN = ['子', '癸', '丑', '艮', '寅', '甲', '卯', '乙', '辰', '巽', '巳', '丙',
       '午', '丁', '未', '坤', '申', '庚', '酉', '辛', '戌', '乾', '亥', '壬']
MTN_EL = {}
for i, m in enumerate(MTN):
    MTN_EL[i * 15] = None
# 直接用山->五行映射（与 MOUNTAINS_24 一致）
SHAN_EL = {
    0: '水', 15: '水', 330: '水', 345: '水',          # 壬癸子亥
    30: '土', 45: '土', 120: '土', 135: '土', 210: '土', 225: '土', 300: '土', 315: '土',
    60: '木', 75: '木', 90: '木', 105: '木', 135: '木',
    150: '火', 165: '火', 180: '火', 195: '火',
    240: '金', 255: '金', 270: '金', 285: '金', 315: '金',
}
TERM = {}
for s, items in SEASON:
    for a, n in items:
        TERM[a] = (n, s)

conflict = 0
for d in range(0, 360, 15):
    el = SHAN_EL.get(d, '?')
    tn, se = TERM.get(d, ('-', '-'))
    # 五行色 vs 节气色
    el_c = EL_COLOR.get(el, '?')
    se_c = SE_COLOR.get(se, '?')
    same = el_c == se_c or (el == '木' and se == '春') or (el == '火' and se == '夏') \
        or (el == '水' and se == '冬') or (el == '金' and se == '秋')
    if same:
        conflict += 1
    print('  %3d°   %-4s     %-6s    %-4s %-9s %s' % (
        d, MTN[d // 15], el, tn, se_c, '★ 同色 → 读成"一个色被切两半"' if same else ''))

print()
print('  同色冲突格数：%d / 24' % conflict)
print()
print('=' * 84)
print('结论')
print('=' * 84)
print('  1) 五行环几何是对的、只有一圈（r1..r2），扇区边界严格对齐 15° 山格。')
print('  2) 用户看到的"第二个环"是紧邻的节气环（r2..r3），它按季节着色，')
print('     而季节色与五行色几乎一一对应（春=木绿、夏=火红、秋=金黄、冬=水蓝）。')
print('  3) "错位"来自两环色块起止角不同：')
print('     木 60~120 而 春 45~120  → 绿色在内环 60° 才开始，外环 45° 就已是绿字')
print('     金 240~300 而 秋 225~300 → 黄色在内环 240° 才开始，外环 225° 就已是黄字')
print('     同一颜色在内环晚 15° 出现、在外环早 15° 出现 → 视觉上像"色带错位半格"。')
print('  4) 放大后截图中"两条色带夹着金线"的观感，就是')
print('     内环扇区填色(0.16 alpha 很淡) + 外环节气文字色(高饱和) 两条不同半径的色带。')
